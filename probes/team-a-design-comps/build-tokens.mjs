#!/usr/bin/env node
// Generates the comp pack's tokens.css from the Ergon pack's design/tokens.json (single source).
// Usage: node build-tokens.mjs --tokens /path/to/design/tokens.json [--out tokens.css]
// Exit 0: written. 1: failed. 2: usage. Workspace tooling only; not part of any product.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const opt = {};
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--tokens' || argv[i] === '--out') { const v = argv[++i]; if (!v) { console.error(`${argv[i - 1]} needs a value`); process.exit(2); } opt[argv[i - 1].slice(2)] = v; }
  else { console.error(`unknown argument: ${argv[i]}\nUsage: node build-tokens.mjs --tokens PATH [--out FILE]`); process.exit(2); }
}
if (!opt.tokens) { console.error('Usage: node build-tokens.mjs --tokens PATH [--out FILE]'); process.exit(2); }
const out = opt.out ?? path.join(HERE, 'tokens.css');
const kebab = (n) => n.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const tokens = JSON.parse(fs.readFileSync(opt.tokens, 'utf8'));
const lines = [];
lines.push('/* GENERATED by build-tokens.mjs from the Ergon design pack design/tokens.json — do not hand-edit.');
lines.push('   Design comps for grading, not built surfaces. No external assets. */');
const vars = [];
for (const [name, value] of Object.entries(tokens.color)) vars.push(`--${kebab(name)}:${value.toUpperCase()}`);
for (const name of tokens.wash.of) {
  const hex = tokens.color[name].replace('#', '');
  const r = parseInt(hex.slice(0, 2), 16), g = parseInt(hex.slice(2, 4), 16), b = parseInt(hex.slice(4, 6), 16);
  vars.push(`--${kebab(name)}-wash:rgba(${r},${g},${b},${(tokens.wash.alpha / 255).toFixed(2)})`);
}
vars.push(`--body:${tokens.type.it.body}px`, `--heading:${tokens.type.it.heading}px`, `--caption:${tokens.type.it.caption}px`);
vars.push(`--ember-body:${tokens.type.employee.body}px`, `--ember-heading:${tokens.type.employee.heading}px`, `--ember-caption:${tokens.type.employee.caption}px`);
vars.push(`--radius:${tokens.radius.panel}px`, `--radius-sm:${tokens.radius.control}px`, `--radius-pill:999px`);
vars.push(`--target:${tokens.target.min}px`, `--target-employee:${tokens.target.employee}px`);
vars.push(`--space-1:${tokens.space[0]}px`, `--space-2:${tokens.space[1]}px`, `--space-3:${tokens.space[2]}px`, `--space-4:${tokens.space[3]}px`, `--space-5:${tokens.space[4]}px`);
vars.push(`--ui:"${tokens.type.family}",system-ui,sans-serif`, `--mono:"${tokens.type.mono}",ui-monospace,monospace`);
lines.push(`:root{color-scheme:dark;${vars.join(';')}}`);
fs.writeFileSync(out, lines.join('\n') + '\n');
if (tokens.color === undefined) { console.error('tokens file has no color block'); process.exit(1); }
console.log(`tokens.css written: ${out} (${vars.length} properties from ${opt.tokens})`);
