#!/usr/bin/env bash
# R0 preflight for the Job 03 RHL dress rehearsal — generic host.
# Writes the R0 evidence files into OUTDIR. Read-only on the host except OUTDIR (its own evidence); no sudo,
# no network calls, no secret handling: it never reads, prints or stores a credential value.
#
# Usage: bash r0-preflight.sh OUTDIR [--repo PATH] [--package TARBALL] [--url NAME]
#   OUTDIR            evidence directory (usually <pass>/R0-pre); created if absent
#   --repo PATH       ergon checkout on the tree pinned for the run (enables run-config check + commit pin)
#   --package TARBALL package tarball to hash (name + SHA-256 recorded)
#   --url NAME        the shareable non-localhost URL name (DNS check is offline: resolution only)
#
# Exit 0: all blocking checks pass (prints "R0 PREFLIGHT: PASS").
# Exit 1: at least one blocking check failed (each named). Exit 2: usage.
set -u

OUTDIR=""
REPO=""
PACKAGE=""
URLNAME=""
while [ $# -gt 0 ]; do
  case "$1" in
    --repo) REPO="${2:-}"; shift 2 ;;
    --package) PACKAGE="${2:-}"; shift 2 ;;
    --url) URLNAME="${2:-}"; shift 2 ;;
    --help|-h) sed -n '2,14p' "$0"; exit 0 ;;
    -*) printf 'unknown argument: %s\n' "$1" >&2; exit 2 ;;
    *) OUTDIR="$1"; shift ;;
  esac
done
if [ -z "$OUTDIR" ]; then printf 'usage: bash r0-preflight.sh OUTDIR [--repo PATH] [--package TARBALL] [--url NAME]\n' >&2; exit 2; fi

mkdir -p "$OUTDIR" || { printf 'cannot create %s\n' "$OUTDIR" >&2; exit 2; }
FAIL=0
say() { printf '%s\n' "$*" | tee -a "$OUTDIR/notes.md" >/dev/null; }
pass() { printf 'PASS  %s\n' "$*"; }
fail() { printf 'FAIL  %s\n' "$*"; FAIL=$((FAIL+1)); }

STAMP="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
{
  printf '# R0 preflight run — generated evidence\n'
  printf '%s\n' "- Generated (UTC): $STAMP"
  printf '%s\n' "- Hostname: $(hostname 2>/dev/null || echo unknown)"
  printf '%s\n' "- Blocking failures: (see summary at end)"
} > "$OUTDIR/preflight-summary.txt"

# 1. Host fingerprint (read-only commands only).
{
  printf '# Host fingerprint — generated by r0-preflight.sh\n'
  printf 'generated_utc: %s\n' "$STAMP"
  printf '\n## uname -a\n'; uname -a 2>&1
  printf '\n## os release\n'; (cat /etc/os-release 2>/dev/null || true)
  printf '\n## hostnamectl (optional)\n'; (hostnamectl 2>/dev/null || echo 'hostnamectl not available')
  printf '\n## cpu / memory / disk\n'; printf 'nproc: '; nproc 2>/dev/null || echo unknown
  (free -g 2>/dev/null || true); (df -h / 2>/dev/null || true)
  printf '\n## time sync\n'; (timedatectl 2>/dev/null || date -u)
  printf '\n## node\n'; (node --version 2>/dev/null || echo 'node not found')
  printf '\n## git (repo pin)\n'
  if [ -n "$REPO" ]; then (git -C "$REPO" rev-parse HEAD 2>/dev/null || echo 'repo not a git checkout'); else echo 'no --repo given'; fi
} > "$OUTDIR/host-fingerprint.txt" 2>&1
[ -s "$OUTDIR/host-fingerprint.txt" ] && pass "host fingerprint written" || fail "host fingerprint not written"

# 2. Package hash (file name + SHA-256 only; no credential material).
if [ -n "$PACKAGE" ] && [ -f "$PACKAGE" ]; then
  { printf '# Package identity — generated by r0-preflight.sh\n'
    printf 'file: %s\n' "$(basename "$PACKAGE")"
    printf 'sha256: %s\n' "$(sha256sum "$PACKAGE" | cut -d' ' -f1)"
    printf 'generated_utc: %s\n' "$STAMP"; } > "$OUTDIR/package-sha256.txt"
  pass "package hashed: $(basename "$PACKAGE") $(sha256sum "$PACKAGE" | cut -d' ' -f1)"
else
  printf '# Package identity — NOT RECORDED (no --package given or file missing)\n' > "$OUTDIR/package-sha256.txt"
  fail "package hash not recorded (R0 blocking: pass --package TARBALL)"
fi

# 3. Run-config acceptance (models + sole route budget-proxy) + repo pin.
if [ -n "$REPO" ] && [ -f "$REPO/docs/acceptance/demo-company/fixtures/check-run-config.mjs" ]; then
  { printf '# Run-config check — generated by r0-preflight.sh\n'
    printf 'command: node docs/acceptance/demo-company/fixtures/check-run-config.mjs (cwd: %s)\n' "$REPO"
    printf 'generated_utc: %s\n\n' "$STAMP"
    (cd "$REPO" && node docs/acceptance/demo-company/fixtures/check-run-config.mjs 2>&1)
    printf '\nexit: %s\n' "$?"; } > "$OUTDIR/run-config-check.txt"
  if grep -q '^accepted: .*route budget-proxy' "$OUTDIR/run-config-check.txt"; then
    pass "run config accepted (route budget-proxy)"
  else
    fail "run config NOT accepted — see run-config-check.txt"
  fi
else
  printf '# Run-config check — NOT RUN (no --repo given or fixtures not found)\n' > "$OUTDIR/run-config-check.txt"
  fail "run-config check not run (R0 blocking: pass --repo PATH to the pinned checkout)"
fi

# 4. Company state must be absent on a fresh host (paths are the deploy conventions; override with ERGON_STATE_PATHS).
STATE_PATHS="${ERGON_STATE_PATHS:-/srv/ergon /opt/ergon /var/lib/ergon /etc/ergon}"
{
  printf '# Absence of company state — generated by r0-preflight.sh\n'
  printf 'generated_utc: %s\n' "$STAMP"
  for p in $STATE_PATHS; do
    if [ -e "$p" ]; then printf 'PRESENT %s\n' "$p"; else printf 'absent  %s\n' "$p"; fi
  done
} > "$OUTDIR/absence-of-company-state.txt"
if grep -q '^PRESENT ' "$OUTDIR/absence-of-company-state.txt"; then
  fail "company state PRESENT on a host that should be fresh — see absence-of-company-state.txt"
else
  pass "no company state on the checked paths"
fi

# 5. URL name (offline resolution only; no HTTP call, no secret).
if [ -n "$URLNAME" ]; then
  { printf '# Shareable URL identity — generated by r0-preflight.sh\n'
    printf 'url_name: %s\n' "$URLNAME"
    printf 'resolution (offline getent): %s\n' "$(getent hosts "$URLNAME" 2>/dev/null | head -1 || echo 'no local resolution')"
    printf 'note: the real reachability check is done from the second device at R3; localhost/raw-IP names are invalid.\n'
    printf 'generated_utc: %s\n' "$STAMP"; } > "$OUTDIR/url.txt"
  case "$URLNAME" in
    localhost|127.*|::1) fail "url name is localhost/loopback — not a shareable company URL" ;;
    *) pass "url name recorded: $URLNAME" ;;
  esac
else
  printf '# Shareable URL identity — NOT RECORDED (no --url given)\n' > "$OUTDIR/url.txt"
  printf 'note  url name not recorded yet (not blocking R0 if DNS is arranged before the clock)\n'
fi

# 6. Project id file is created by the provisioning owner (id/region only, never a key).
if [ -f "$OUTDIR/project-id.txt" ] && ! grep -q 'templated at filing' "$OUTDIR/project-id.txt" 2>/dev/null; then
  pass "company project id recorded"
else
  printf '# Company project — NOT RECORDED\n<templated at filing; the provisioning owner writes the project id and region only — never a key, URL token or password>\n' > "$OUTDIR/project-id.txt"
  fail "company project id not recorded (R0 blocking: write id + region only, no secret)"
fi

{
  printf '\n# Summary\n'
  printf 'generated_utc: %s\n' "$STAMP"
  if [ "$FAIL" -eq 0 ]; then printf 'result: PASS (0 blocking failures)\n'; else printf 'result: FAIL (%s blocking failures)\n' "$FAIL"; fi
} >> "$OUTDIR/preflight-summary.txt"

printf '\n'
if [ "$FAIL" -eq 0 ]; then printf 'R0 PREFLIGHT: PASS\n'; exit 0; fi
printf 'R0 PREFLIGHT: FAIL (%s blocking)\n' "$FAIL"; exit 1
