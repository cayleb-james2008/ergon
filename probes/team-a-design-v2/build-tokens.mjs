#!/usr/bin/env node
/**
 * Generates tokens.css from tokens.json. The ONLY place colour/type/motion literals are allowed to live is tokens.json;
 * every comp, kit and script consumes the generated custom properties. Run: node build-tokens.mjs (also writes a temp
 * comparison target used by check-comps.mjs via --check).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase().replace(/_/g, '-');

export function build(tokens) {
  const lines = [];
  lines.push('/* GENERATED by build-tokens.mjs from tokens.json — do not hand-edit.');
  lines.push('   Ergon Lumen v2 direction proposal. DESIGN COMP — NOT A BUILT SURFACE. */');
  lines.push(':root {');
  lines.push('  color-scheme: dark;');

  const colorGroups = {
    color: (v) => v,
  };
  for (const [key, value] of Object.entries(tokens.color)) {
    lines.push(`  --${kebab(key)}: ${value};`);
  }
  for (const [key, value] of Object.entries(tokens.blur)) {
    lines.push(`  --blur-${kebab(key)}: ${value};`);
  }
  for (const [key, value] of Object.entries(tokens.depth)) {
    lines.push(`  --depth-${kebab(key)}: ${value};`);
  }
  for (const [key, value] of Object.entries(tokens.radius)) {
    lines.push(`  --radius-${kebab(key)}: ${value};`);
  }
  tokens.space.forEach((value, i) => lines.push(`  --space-${i + 1}: ${value};`));
  lines.push(`  --ui: ${tokens.type.family};`);
  lines.push(`  --mono: ${tokens.type.mono};`);
  lines.push(`  --body: ${tokens.type.itBody};`);
  lines.push(`  --heading: ${tokens.type.itHeading};`);
  lines.push(`  --caption: ${tokens.type.itCaption};`);
  lines.push(`  --emp-body: ${tokens.type.employeeBody};`);
  lines.push(`  --emp-heading: ${tokens.type.employeeHeading};`);
  lines.push(`  --emp-caption: ${tokens.type.employeeCaption};`);
  lines.push(`  --fs-label: ${tokens.type.label};`);
  lines.push(`  --fs-display: ${tokens.type.display};`);
  lines.push(`  --target: ${tokens.target.min};`);
  lines.push(`  --target-employee: ${tokens.target.employee};`);
  lines.push(`  --motion-tap: ${tokens.motion.tap};`);
  lines.push(`  --motion-swap: ${tokens.motion.swap};`);
  lines.push(`  --motion-enter: ${tokens.motion.enter};`);
  lines.push(`  --motion-sheet: ${tokens.motion.sheet};`);
  lines.push(`  --ease: ${tokens.motion.ease};`);
  lines.push(`  --focus-ring: ${tokens.focus.ring};`);
  lines.push(`  --focus-gap: ${tokens.focus.gap};`);
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(fs.readFileSync(path.join(HERE, 'tokens.json'), 'utf8'));
  const css = build(tokens);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(path.join(HERE, 'tokens.css')) ? fs.readFileSync(path.join(HERE, 'tokens.css'), 'utf8') : '';
    if (current !== css) {
      process.stdout.write('TOKENS: STALE — tokens.css does not match tokens.json; run node build-tokens.mjs\n');
      process.exit(1);
    }
    process.stdout.write('TOKENS: CURRENT — tokens.css matches tokens.json\n');
  } else {
    fs.writeFileSync(path.join(HERE, 'tokens.css'), css);
    process.stdout.write('tokens.css written from tokens.json\n');
  }
}
